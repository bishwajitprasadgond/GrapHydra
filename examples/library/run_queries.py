"""Run every example in queries.ghql (or writes.ghql) and print the results.

    python examples/library/run_queries.py             # read-only examples
    python examples/library/run_queries.py --writes    # write examples, on a temporary copy
    python examples/library/run_queries.py --results   # regenerate RESULTS.md

Build the graph first with build_library.py.
"""

import re
import shutil
import sys
import tempfile
from pathlib import Path

from graphydra import Graph, Node, Path as GraphPath

HERE = Path(__file__).resolve().parent
TITLE = re.compile(r"^// (\d+)\. (.+)$")


def examples(script: Path) -> list[tuple[str, str]]:
    """Split a script into (title, statement) pairs using its "// N. Title" comments."""
    out: list[tuple[str, str]] = []
    title, lines = None, []
    for line in script.read_text(encoding="utf-8").splitlines():
        match = TITLE.match(line)
        if match:
            title, lines = f"{match[1]}. {match[2]}", []
        elif title and not line.startswith("//"):
            lines.append(line)
            if line.rstrip().endswith(";"):
                out.append((title, "\n".join(lines).strip().rstrip(";")))
                title = None
    return out


def show(value: object) -> str:
    if isinstance(value, Node):
        return f"({value.id})"
    if isinstance(value, GraphPath):
        return " - ".join(n.id for n in value.nodes)
    if isinstance(value, list):
        return "[" + ", ".join(show(v) for v in value) + "]"
    return str(value)


def table(columns: list[str], rows: list[tuple]) -> str:
    cells = [[show(v) for v in row] for row in rows]
    widths = [min(100, max([len(c)] + [len(r[i]) for r in cells])) for i, c in enumerate(columns)]
    fmt = lambda vals: "| " + " | ".join(v[:100].ljust(w) for v, w in zip(vals, widths)) + " |"  # noqa: E731
    lines = [fmt(columns), "|" + "|".join("-" * (w + 2) for w in widths) + "|"]
    lines += [fmt(r) for r in cells]
    return "\n".join(lines)


def render(path: Path, script: Path, writes: bool) -> str:
    """Run every example in `script` against `path`; return the Markdown report."""
    out: list[str] = []
    with Graph.open(path, read_only=not writes) as g:
        for title, statement in examples(script):
            result = g.query(statement, read_only=not writes)
            out.append(f"### {title}\n\n```cypher\n{statement}\n```\n")
            if result.columns:
                out.append(table(result.columns, result.rows))
            else:
                kinds = ("_created", "_deleted", "_set", "_added", "_removed")
                changes = ", ".join(f"{k} {v}" for k, v in result.stats.items() if k.endswith(kinds) and v)
                out.append(f"No rows returned. Changes: {changes or 'none'}.")
            out.append("")
    return "\n".join(out)


def results(source: Path) -> str:
    """The full RESULTS.md: read examples, then write examples on a copy."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "library.graph"
        shutil.copy(source, copy)
        return "\n".join(
            [
                "# Example results",
                "",
                "Generated by `python examples/library/run_queries.py --results`; do not edit by hand.",
                "",
                "## Read queries (`queries.ghql`)",
                "",
                render(source, HERE / "queries.ghql", writes=False),
                "## Write queries (`writes.ghql`, applied in order to a copy)",
                "",
                render(copy, HERE / "writes.ghql", writes=True),
            ]
        )


def main() -> None:
    source = HERE / "library.graph"
    if not source.exists():
        sys.exit("library.graph not found: run build_library.py first")
    if "--results" in sys.argv:
        (HERE / "RESULTS.md").write_text(results(source), encoding="utf-8")
        print(f"wrote {HERE / 'RESULTS.md'}")
    elif "--writes" in sys.argv:
        with tempfile.TemporaryDirectory() as tmp:  # never modify the shared example graph
            copy = Path(tmp) / "library.graph"
            shutil.copy(source, copy)
            print(render(copy, HERE / "writes.ghql", writes=True))
    else:
        print(render(source, HERE / "queries.ghql", writes=False))


if __name__ == "__main__":
    main()
